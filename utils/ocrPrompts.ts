/**
 * OCR モードに対応するプロンプトを返す
 */
export function getOcrPrompt(mode: OcrMode): string {
  switch (mode) {
    case "handwriting":
      return HANDWRITING_OCR_PROMPT;
    case "model_answer":
      return MODEL_ANSWER_OCR_PROMPT;
    case "general":
    default:
      return GENERAL_OCR_PROMPT;
  }
}
